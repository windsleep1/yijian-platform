class KnowledgeBase:
    """把 RAW_KPS 展开成带 ID 的知识点与条目索引。"""

    def __init__(self) -> None:
        self.kps: list[dict[str, Any]] = []
        self.items_by_kp: dict[int, list[dict[str, Any]]] = {}
        self.kp_by_chapter: dict[int, list[int]] = {}
        self.items_by_chapter: dict[int, list[dict[str, Any]]] = {}
        self.items_by_subject: dict[str, list[dict[str, Any]]] = {}

        kp_id = KPID_BASE
        item_id = 1

        for kp_name, chapter_id, items in RAW_KPS:
            chapter = CH_ID[chapter_id]
            subject_code = chapter["subject"]
            kp = {
                "id": kp_id,
                "subject_code": subject_code,
                "subject_id": SUBJECTS[subject_code]["id"],
                "chapter_id": chapter_id,
                "code": f"{chapter['code']}-{len(self.kp_by_chapter.get(chapter_id, [])) + 1:03d}",
                "name": kp_name,
            }
            self.kps.append(kp)
            self.kp_by_chapter.setdefault(chapter_id, []).append(kp_id)
            bucket: list[dict[str, Any]] = []

            for term, definition in items:
                item = {
                    "id": item_id,
                    "kp_id": kp_id,
                    "chapter_id": chapter_id,
                    "subject_code": subject_code,
                    "term": term,
                    "definition": definition,
                }
                bucket.append(item)
                self.items_by_chapter.setdefault(chapter_id, []).append(item)
                self.items_by_subject.setdefault(subject_code, []).append(item)
                item_id += 1

            self.items_by_kp[kp_id] = bucket
            kp_id += 1

    def kps_of_subject(self, subject_code: str) -> list[dict[str, Any]]:
        return [kp for kp in self.kps if kp["subject_code"] == subject_code]

    def distractor_pool(self, item: dict[str, Any], size: int) -> list[dict[str, Any]]:
        """
        取干扰项池：优先同章节，不足则扩展到同科目。
        干扰项与正确项必须在语义上不同（术语互不相同），保证答案唯一。
        """
        same_chapter = [
            x for x in self.items_by_chapter.get(item["chapter_id"], [])
            if x["id"] != item["id"]
        ]
        if len(same_chapter) >= size:
            return same_chapter
        same_subject = [
            x for x in self.items_by_subject.get(item["subject_code"], [])
            if x["id"] != item["id"]
        ]
        merged = same_chapter + [x for x in same_subject if x not in same_chapter]
        return merged


