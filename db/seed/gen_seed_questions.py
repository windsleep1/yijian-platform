    print("题目分布（按科目）：")
    for code, cnt in sorted(manifest["by_subject"].items(), key=lambda x: -x[1]):
        s = SUBJECTS[code]
        print(f"      {s['short']:<10} {cnt:>6} 道")
    print()
    print("题目分布（按题型）：")
    for t, cnt in sorted(manifest["by_type"].items(), key=lambda x: -x[1]):
        print(f"      {TYPE_LABEL.get(t, t):<10} {cnt:>6} 道")
    print()
    print(f"总计 {manifest['totals']['questions']} 道题 / "
          f"{manifest['totals']['options']} 个选项 / 耗时 {elapsed_ms / 1000:.2f}s")
    print(f"内容指纹 {manifest['fingerprint'][:16]}…（同 seed 可复现）")
