def normalize_for_hash(text: str) -> str:
    """归一化文本，用于内容指纹计算。与 docs/03 第 4.1 节算法完全一致。"""
    if not text:
        return ""
    s = unicodedata.normalize("NFKC", text)          # 全角转半角
    s = s.replace("\u3000", " ")                      # 全角空格
    s = re.sub(r"<[^>]+>", "", s)                     # 去 HTML 标签
    s = re.sub(r"[\s\u200b]+", "", s)                 # 去空白与零宽字符
    s = re.sub(r"[（(]\s*[)）]", "", s)                # 去空括号
    s = re.sub(r"[，,。.；;：:！!？?、]", "", s)         # 去标点
    return s.lower()


def content_hash(stem: str, options: list[tuple[str, str]], qtype: str) -> str:
    """计算题目内容指纹（SHA-256），用于去重。"""
    parts = [qtype, normalize_for_hash(stem)]
    for label, content in sorted(options):
        parts.append(f"{label}:{normalize_for_hash(content)}")
    return hashlib.sha256("||".join(parts).encode("utf-8")).hexdigest()


def sql_escape(value: str) -> str:
    """转义 SQL 单引号（standard_conforming_strings=on 下只需处理单引号）。"""
    return value.replace("'", "''")


def sql_text(value: str | None) -> str:
    """
    把 Python 字符串转成 PostgreSQL 文本字面量。

    - 不含换行/制表符：使用普通字符串 '...'（反斜杠按字面处理）
    - 含换行/制表符：使用转义字符串 E'...' 并转义为 \\n / \\r / \\t，
      这样每条 INSERT 保持单行，便于版本管理与逐行排查，且语义完全等价。
    """
    if value is None:
        return "NULL"
    if any(ch in value for ch in "\n\r\t"):
        escaped = value.replace("\\", "\\\\").replace("'", "''")
        escaped = (escaped.replace("\r\n", "\\n").replace("\n", "\\n")
                          .replace("\r", "\\r").replace("\t", "\\t"))
        return "E'" + escaped + "'"
    return "'" + value.replace("'", "''") + "'"


def jsonb_literal(value: Any) -> str:
    """生成 SQL 中的 jsonb 字面量。"""
    raw = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    return "'" + sql_escape(raw) + "'::jsonb"


def pick_difficulty(qtype: str, seed_text: str) -> int:
    """按题型给出难度区间，用内容指纹做确定性抖动，保证可复现。"""
    lo, hi = DIFFICULTY_RANGE.get(qtype, (2, 3))
    digest = int(hashlib.md5(seed_text.encode("utf-8")).hexdigest()[:8], 16)
    return lo + (digest % (hi - lo + 1))


