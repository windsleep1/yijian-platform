class Generator:
    def __init__(self, kb: KnowledgeBase, seed: int, enable_case: bool = True,
                 only_subjects: list[str] | None = None) -> None:
        self.kb = kb
        self.rng = random.Random(seed)
        self.enable_case = enable_case
        self.subjects = only_subjects or list(SUBJECTS.keys())
        self.seen_hashes: set[str] = set()
        self.questions: list[dict[str, Any]] = []
        self.options: list[dict[str, Any]] = []
        self._qid = QID_BASE
        self._oid = OPTID_BASE
        self._case_seq = 0

    # ---------------- ID 分配 ----------------

    def _next_qid(self) -> int:
        self._qid += 1
        return self._qid

    def _next_oid(self) -> int:
        self._oid += 1
        return self._oid

    # ---------------- 落库前统一组装 ----------------

    def _emit(
        self,
        *,
        subject_code: str,
        chapter_id: int,
        kp_id: int | None,
        qtype: str,
        stem: str,
        options: list[tuple[str, str]],
        answer_value: list,
        analysis: str,
        tags: list[str],
        parent_id: int | None = None,
        root_id: int | None = None,
        sort_no: int = 0,
        material_html: str | None = None,
        analysis_points: list[dict[str, Any]] | None = None,
    ) -> int | None:
        """组装并收集一道题。返回题目 ID；若判定为重复则返回 None。"""
        # 判断题选项固定为 A. 正确 / B. 错误
        if qtype == "judge":
            options = [("A", "正确"), ("B", "错误")]

        digest = content_hash(stem, options, qtype)
        if digest in self.seen_hashes:
            return None
        self.seen_hashes.add(digest)

        qid = self._next_qid()
        # 存在性校验（原先写成 `chapter = CH_ID[chapter_id]` 但结果没人用，ruff F841）。
        # ⚠️ 不能直接删成"什么都不做"—— 那样章节缺失时不会当场炸，
        # 而是生成出**悬空引用**（题目指向一个不存在的章节）。保留 fail-fast。
        if chapter_id not in CH_ID:
            raise KeyError(f"章节 {chapter_id} 不在种子章节表 CH_ID 里")
        subject = SUBJECTS[subject_code]

        self.questions.append({
            "id": qid,
            "subject_id": subject["id"],
            "subject_code": subject_code,
            "chapter_id": chapter_id,
            "knowledge_point_id": kp_id,
            "type": qtype,
            "stem": stem,
            "answer": {"value": answer_value},
            "analysis": analysis,
            "analysis_points": analysis_points or [],
            "options_snapshot": [{"label": lb, "content": ct} for lb, ct in options],
            "score_default": 1.0 if qtype != "case_sub" else 2.0,
            "difficulty": pick_difficulty(qtype, digest),
            "exam_year": None,
            "source_type": "self",
            "source_name": SEED_BANK_NAME,
            "source_license": "自有原创内容，无第三方授权",
            "tags": tags,
            "parent_id": parent_id,
            "root_id": root_id if root_id is not None else qid,
            "sort_no": sort_no,
            "material_html": material_html,
            "content_hash": digest,
            "status": "published",
        })

        for idx, (label, content) in enumerate(options):
            self.options.append({
                "id": self._next_oid(),
                "question_id": qid,
                "label": label,
                "content": content,
                "is_correct": label in answer_value,
                "sort_no": idx,
            })
        return qid

    # ---------------- 各题型生成 ----------------

    def gen_judge(self, item: dict[str, Any], variant: int) -> None:
        """判断题：正确项用自身释义；错误项用同章节其他术语的释义。"""
        kp = next(k for k in self.kb.kps if k["id"] == item["kp_id"])
        chapter = CH_ID[item["chapter_id"]]

        if variant % 2 == 0:
            stem = f"{item['term']}是指{item['definition']}。"
            analysis = (
                f"表述正确。{item['term']}的确是指{item['definition']}。"
                f"该知识点属于《{SUBJECTS[item['subject_code']]['name']}》{chapter['name']}中「{kp['name']}」的内容。"
            )
            answer = ["A"]
        else:
            others = [x for x in self.kb.items_by_chapter.get(item["chapter_id"], [])
                      if x["id"] != item["id"] and x["term"] != item["term"]]
            if not others:
                return
            wrong = self.rng.choice(others)
            stem = f"{item['term']}是指{wrong['definition']}。"
            analysis = (
                f"表述错误。{wrong['definition']}是对「{wrong['term']}」的表述，"
                f"而{item['term']}是指{item['definition']}。二者属于不同概念，注意区分。"
            )
            answer = ["B"]

        self._emit(
            subject_code=item["subject_code"], chapter_id=item["chapter_id"], kp_id=item["kp_id"],
            qtype="judge", stem=stem, options=[], answer_value=answer, analysis=analysis,
            tags=["仿真题", "判断题", kp["name"]],
        )

    def gen_single_def_to_term(self, item: dict[str, Any], variant: int) -> None:
        """单选：给释义，选出对应术语。"""
        kp = next(k for k in self.kb.kps if k["id"] == item["kp_id"])
        if item["chapter_id"] not in CH_ID:  # 同 790：存在性校验（原先是一次无人使用的查表）
            raise KeyError(f"章节 {item['chapter_id']} 不在种子章节表 CH_ID 里")
        pool = self.kb.distractor_pool(item, 3)
        if len(pool) < 3:
            return
        distractors = self.rng.sample(pool, 3)
        # 用 variant 对选项顺序做确定性扰动，产生不同题干排列而不改变语义
        order = [item] + distractors
        self.rng.shuffle(order)
        labels = OPTION_LABELS[:4]
        opts = [(labels[i], o["term"]) for i, o in enumerate(order)]
        correct_label = next(lb for lb, ct in opts if ct == item["term"])

        stem = f"下列各项中，「{item['definition']}」描述的是（　　）。"
        analysis = (
            f"正确答案为 {correct_label}。{item['term']}是指{item['definition']}。\n"
            + "".join(
                f"{label}. {opt_item['term']}：其含义为「{opt_item['definition']}」，"
                f"与题干给出的释义不是同一概念。\n"
                for label, opt_item in zip(labels, order)
                if opt_item["term"] != item["term"]
            )
        ).rstrip()
        self._emit(
            subject_code=item["subject_code"], chapter_id=item["chapter_id"], kp_id=item["kp_id"],
            qtype="single", stem=stem, options=opts, answer_value=[correct_label],
            analysis=analysis, tags=["仿真题", "单选题", kp["name"]],
        )

    def gen_single_term_to_def(self, item: dict[str, Any], variant: int) -> None:
        """单选：给术语，选出正确释义。"""
        kp = next(k for k in self.kb.kps if k["id"] == item["kp_id"])
        pool = self.kb.distractor_pool(item, 3)
        if len(pool) < 3:
            return
        distractors = self.rng.sample(pool, 3)
        order = [item] + distractors
        self.rng.shuffle(order)
        labels = OPTION_LABELS[:4]
        opts = [(labels[i], o["definition"]) for i, o in enumerate(order)]
        correct_label = next(lb for lb, ct in opts if ct == item["definition"])

        stem = f"关于「{item['term']}」，下列表述正确的是（　　）。"
        analysis = (
            f"正确答案为 {correct_label}。{item['term']}是指{item['definition']}。\n"
            + "".join(
                f"{label}. 该表述是对「{opt_item['term']}」的描述，"
                f"并非「{item['term']}」的定义。\n"
                for label, opt_item in zip(labels, order)
                if opt_item["term"] != item["term"]
            )
        ).rstrip()
        self._emit(
            subject_code=item["subject_code"], chapter_id=item["chapter_id"], kp_id=item["kp_id"],
            qtype="single", stem=stem, options=opts, answer_value=[correct_label],
            analysis=analysis, tags=["仿真题", "单选题", kp["name"]],
        )

    def gen_multiple(self, item: dict[str, Any], variant: int) -> None:
        """多选：正确项取自**同一知识点**下的其他条目，干扰项取自同科目其他章节。
        这样「属于该考点范畴」的判定在逻辑上成立，答案唯一且无歧义。"""
        kp = next(k for k in self.kb.kps if k["id"] == item["kp_id"])
        same_kp = [
            x for x in self.kb.items_by_kp.get(item["kp_id"], [])
            if x["term"] != item["term"]
        ]
        if len(same_kp) < 2:
            return
        other_chapter = [
            x for x in self.kb.items_by_subject.get(item["subject_code"], [])
            if x["chapter_id"] != item["chapter_id"]
        ]
        if len(other_chapter) < 2:
            return

        n_correct = self.rng.choice([2, 3])
        if len(same_kp) < n_correct:
            n_correct = len(same_kp)
        n_wrong = 4 - n_correct
        correct_items = self.rng.sample(same_kp, n_correct)
        wrong_items = self.rng.sample(other_chapter, n_wrong)

        all_items = correct_items + wrong_items
        self.rng.shuffle(all_items)
        labels = OPTION_LABELS[:len(all_items)]
        opts = [(labels[i], o["term"]) for i, o in enumerate(all_items)]
        correct_terms = {o["term"] for o in correct_items}
        answer = [lb for lb, ct in opts if ct in correct_terms]

        stem = (
            f"下列选项中，属于「{kp['name']}」这一考点所涵盖内容的有（　　）。"
        )
        analysis = (
            f"正确答案为 {'、'.join(answer)}。\n"
            + "".join(f"{lb}. {ct}：属于「{kp['name']}」涵盖的概念。\n"
                      for lb, ct in opts if lb in answer)
            + "".join(f"{lb}. {ct}：属于其他章节的内容，不在本考点范围内。\n"
                      for lb, ct in opts if lb not in answer)
        ).rstrip()

        self._emit(
            subject_code=item["subject_code"], chapter_id=item["chapter_id"], kp_id=item["kp_id"],
            qtype="multiple", stem=stem, options=opts, answer_value=answer,
            analysis=analysis, tags=["仿真题", "多选题", kp["name"]],
        )

    # ---------------- 案例题（实务科目） ----------------

    def gen_case(self, subject_code: str) -> None:
        """生成一道案例题（1 个根题 + 3 个小问）。仅实务科目。"""
        materials = CASE_MATERIALS.get(subject_code)
        if not materials:
            return
        kps = self.kb.kps_of_subject(subject_code)
        if len(kps) < 3:
            return

        self._case_seq += 1
        group_id = f"CASE-{subject_code}-{self._case_seq:04d}"
        material = f"【背景资料】{self.rng.choice(materials)}（案例编号 {group_id}）"
        chapter_id = self.rng.choice([k["chapter_id"] for k in kps])

        root_id = self._next_qid()
        digest = content_hash(material, [], "case")
        if digest in self.seen_hashes:
            self._qid -= 1
            return
        self.seen_hashes.add(digest)
        self.questions.append({
            "id": root_id,
            "subject_id": SUBJECTS[subject_code]["id"],
            "subject_code": subject_code,
            "chapter_id": chapter_id,
            "knowledge_point_id": None,
            "type": "case",
            "stem": material,
            "answer": {"value": "见各小问参考答案"},
            "analysis": "本题为案例题，请结合背景资料与相关规范逐问作答。",
            "analysis_points": [],
            "options_snapshot": [],
            "score_default": 20.0,
            "difficulty": 4,
            "exam_year": None,
            "source_type": "self",
            "source_name": SEED_BANK_NAME,
            "source_license": "自有原创内容，无第三方授权",
            "tags": ["仿真题", "案例题"],
            "parent_id": None,
            "root_id": root_id,
            "sort_no": 0,
            "material_html": material,
            "content_hash": digest,
            "status": "published",
        })

        n_subs = 3
        picked_kps = self.rng.sample(kps, min(n_subs, len(kps)))
        # 工程情形简述 + 提问句式池：两者组合保证各案例的小问互不重复
        descriptor = material.split("，")[0].replace("【背景资料】", "").strip()
        phrasings = [
            "结合背景资料，指出{term}的含义，并说明其在工程实践中的主要作用。",
            "结合背景资料，简述{term}的含义及其在本工程中的应用要点。",
            "根据相关规范要求，说明{term}的含义，并结合背景资料进行分析。",
        ]
        for i, kp in enumerate(picked_kps, start=1):
            items = self.kb.items_by_kp[kp["id"]]
            if not items:
                continue
            item = self.rng.choice(items)
            phrasing = self.rng.choice(phrasings).format(term=item["term"])
            stem = f"问题{i}：{descriptor}。{phrasing}（{self.rng.choice([4, 5, 6])} 分）"
            points = [
                {"key": "p1", "text": f"准确说明{item['term']}的含义", "score": 2},
                {"key": "p2", "text": "结合工程实际说明其主要作用", "score": 2},
                {"key": "p3", "text": "表述条理清晰、专业术语使用准确", "score": 1},
            ]
            analysis = f"参考答案要点：{item['term']}是指{item['definition']}。"
            self._emit(
                subject_code=subject_code, chapter_id=kp["chapter_id"], kp_id=kp["id"],
                qtype="case_sub", stem=stem, options=[], answer_value=[item["definition"]],
                analysis=analysis, analysis_points=points,
                parent_id=root_id, root_id=root_id, sort_no=i, material_html=material,
                tags=["仿真题", "案例小题", kp["name"]],
            )

    # ---------------- 主循环 ----------------

    def run(self, target: int, case_ratio: float = 0.08) -> None:
        # case_ratio 表示案例题（含小问）占全部题目的比例；每道案例题产生 1 根 + 3 小问
        case_roots_target = int(target * case_ratio / 4) if self.enable_case else 0
        case_roots_done = 0

        # 题目类型循环顺序：保证题型分布均衡
        plan = [
            ("single_def", 4),
            ("single_term", 2),
            ("judge", 2),
            ("multiple", 2),
        ]

        attempts = 0
        max_attempts = target * 60

        while len(self.questions) < target and attempts < max_attempts:
            attempts += 1

            # 按比例插入案例题
            if (
                self.enable_case
                and case_roots_done < case_roots_target
                and self.rng.random() < 0.06
            ):
                pro_subjects = [s for s in self.subjects if SUBJECTS[s]["category"] == "professional"]
                if pro_subjects:
                    before = len(self.questions)
                    self.gen_case(self.rng.choice(pro_subjects))
                    if len(self.questions) > before:
                        case_roots_done += 1
                        continue

            subject_code = self.rng.choice(self.subjects)
            kps = self.kb.kps_of_subject(subject_code)
            if not kps:
                continue
            kp = self.rng.choice(kps)
            items = self.kb.items_by_kp[kp["id"]]
            if not items:
                continue
            item = self.rng.choice(items)

            kind, repeats = self.rng.choice(plan)
            variant = attempts % max(repeats, 1)
            if kind == "judge":
                self.gen_judge(item, variant)
            elif kind == "single_def":
                self.gen_single_def_to_term(item, variant)
            elif kind == "single_term":
                self.gen_single_term_to_def(item, variant)
            elif kind == "multiple":
                self.gen_multiple(item, variant)


