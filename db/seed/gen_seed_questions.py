def write_json(path: Path, questions: list[dict], options: list[dict]) -> None:
    opt_map: dict[int, list[dict]] = {}
    for o in options:
        opt_map.setdefault(o["question_id"], []).append(
            {"label": o["label"], "content": o["content"],
             "is_correct": o["is_correct"], "sort_no": o["sort_no"]}
        )
    payload = []
    for q in questions:
        row = dict(q)
        row["options"] = opt_map.get(q["id"], [])
        payload.append(row)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def write_sql(path: Path, questions: list[dict], options: list[dict]) -> None:
    lines: list[str] = [
        "-- =====================================================================",
        f"-- 一建通 · 原创仿真题库种子数据  ({SEED_BANK_NAME})",
        f"-- 生成时间: {datetime.now(timezone.utc).astimezone().isoformat(timespec='seconds')}",
        f"-- 题目数量: {len(questions)}   选项数量: {len(options)}",
        "-- 合规说明: source_type 全部为 'self'，exam_year 一律为空，未使用任何第三方题库内容。",
        "-- 幂等说明: 使用 ON CONFLICT (content_hash) DO NOTHING，可重复执行。",
        "-- 执行方式: psql -U yijian -d yijian -f questions.sql",
        "-- =====================================================================",
        "",
        "BEGIN;",
        "",
        "-- ---------- 知识点（供题目关联；若已存在则跳过） ----------",
    ]

    # 知识点
    kb = {kp["id"]: kp for kp in _KB_CACHE.kps} if _KB_CACHE else {}
    for kp in kb.values():
        lines.append(
            "INSERT INTO knowledge_points (id, subject_id, chapter_id, code, name, level, path, importance) "
            f"VALUES ({kp['id']}, {kp['subject_id']}, {kp['chapter_id']}, "
            f"{sql_text(kp['code'])}, {sql_text(kp['name'])}, 1, "
            f"{sql_text('/' + str(kp['chapter_id']) + '/' + str(kp['id']) + '/')}, 2) "
            "ON CONFLICT (id) DO NOTHING;"
        )

    lines.append("")
    lines.append("-- ---------- 题目 ----------")

    for q in questions:
        answer_lit = jsonb_literal(q["answer"])
        opts_lit = jsonb_literal(q["options_snapshot"])
        points_lit = jsonb_literal(q["analysis_points"])
        tags_lit = "ARRAY[" + ",".join(
            sql_text(t) for t in q["tags"]
        ) + "]::text[]"
        parent = "NULL" if q["parent_id"] is None else str(q["parent_id"])
        kp_id = "NULL" if q["knowledge_point_id"] is None else str(q["knowledge_point_id"])

        lines.append(
            "INSERT INTO questions (id, subject_id, chapter_id, knowledge_point_id, type, stem, "
            "answer, analysis, analysis_points, options_snapshot, score_default, difficulty, "
            "exam_year, source_type, source_name, source_license, tags, parent_id, root_id, "
            "sort_no, material_html, content_hash, status, published_at) VALUES ("
            f"{q['id']}, {q['subject_id']}, {q['chapter_id']}, {kp_id}, {sql_text(q['type'])}, "
            f"{sql_text(q['stem'])}, {answer_lit}, {sql_text(q['analysis'])}, "
            f"{points_lit}, {opts_lit}, {q['score_default']}, {q['difficulty']}, "
            f"NULL, {sql_text(q['source_type'])}, {sql_text(q['source_name'])}, "
            f"{sql_text(q['source_license'])}, {tags_lit}, {parent}, {q['root_id']}, "
            f"{q['sort_no']}, {sql_text(q['material_html'])}, {sql_text(q['content_hash'])}, "
            f"{sql_text(q['status'])}, now()"
            ") ON CONFLICT (content_hash) WHERE is_deleted = false DO NOTHING;"
        )

    lines.append("")
    lines.append("-- ---------- 选项 ----------")
    for o in options:
        lines.append(
            "INSERT INTO question_options (id, question_id, label, content, is_correct, sort_no) "
            f"VALUES ({o['id']}, {o['question_id']}, {sql_text(o['label'])}, "
            f"{sql_text(o['content'])}, {str(o['is_correct']).lower()}, {o['sort_no']}) "
            "ON CONFLICT (question_id, label) DO NOTHING;"
        )

    lines.append("")
    lines.append("COMMIT;")
    lines.append("")
    lines.append("-- 校验：")
    lines.append("-- SELECT subject_id, type, count(*) FROM questions "
                 "WHERE source_type = 'self' GROUP BY 1, 2 ORDER BY 1, 2;")

    path.write_text("\n".join(lines), encoding="utf-8")


def write_csv(path: Path, questions: list[dict], options: list[dict]) -> None:
    opt_map: dict[int, list[dict]] = {}
    for o in options:
        opt_map.setdefault(o["question_id"], []).append(o)

    headers = [
        "subject_code", "chapter_id", "knowledge_point_id", "type", "stem",
        "option_a", "option_b", "option_c", "option_d", "option_e", "option_f",
        "answer", "analysis", "score", "difficulty",
        "exam_year", "source_type", "source_name", "source_license", "tags",
        "case_group_id", "material",
    ]
    subj_code_by_id = {v["id"]: k for k, v in SUBJECTS.items()}

    with path.open("w", encoding="utf-8-sig", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(headers)
        for q in questions:
            opts = sorted(opt_map.get(q["id"], []), key=lambda x: x["sort_no"])
            opt_cells = [""] * 6
            for o in opts:
                idx = OPTION_LABELS.index(o["label"]) if o["label"] in OPTION_LABELS else -1
                if 0 <= idx < 6:
                    opt_cells[idx] = o["content"]
            writer.writerow([
                subj_code_by_id.get(q["subject_id"], ""),
                q["chapter_id"],
                q["knowledge_point_id"] or "",
                q["type"],
                q["stem"],
                *opt_cells,
                "".join(q["answer"]["value"]) if isinstance(q["answer"]["value"], list) else q["answer"]["value"],
                q["analysis"],
                q["score_default"],
                q["difficulty"],
                q["exam_year"] or "",
                q["source_type"],
                q["source_name"],
                q["source_license"],
                "|".join(q["tags"]),
                "" if q["type"] != "case_sub" else f"ROOT-{q['root_id']}",
                q["material_html"] or "",
            ])


def write_manifest(path: Path, questions: list[dict], options: list[dict],
                   elapsed_ms: int) -> dict:
    by_subject: dict[str, int] = {}
    by_type: dict[str, int] = {}
    by_difficulty: dict[str, int] = {}
    for q in questions:
        by_subject[q["subject_code"]] = by_subject.get(q["subject_code"], 0) + 1
        by_type[q["type"]] = by_type.get(q["type"], 0) + 1
        by_difficulty[str(q["difficulty"])] = by_difficulty.get(str(q["difficulty"]), 0) + 1

    fingerprint = hashlib.sha256(
        "".join(sorted(q["content_hash"] for q in questions)).encode("utf-8")
    ).hexdigest()

    manifest = {
        "bank_name": SEED_BANK_NAME,
        "schema_version": SCHEMA_VERSION,
        "generated_at": datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds"),
        "elapsed_ms": elapsed_ms,
        "totals": {
            "questions": len(questions),
            "options": len(options),
            "knowledge_points": len(_KB_CACHE.kps) if _KB_CACHE else 0,
        },
        "by_subject": by_subject,
        "by_type": by_type,
        "by_difficulty": by_difficulty,
        "compliance": {
            "source_type": "self",
            "exam_year": "全部为空（不伪造年份冒充真题）",
            "third_party_content": "无",
            "note": "全部题目基于公开考纲知识点自行撰写表述，facts 本身不受著作权保护。",
        },
        "fingerprint": fingerprint,
    }
    path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    return manifest


