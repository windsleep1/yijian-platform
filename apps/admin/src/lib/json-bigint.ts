/**
 * 大整数 ID 的解析安全带。
 *
 * ⚠️ 定位：**防御垫，非主路径。**
 *
 * 主路径是**后端把 ID 序列化成字符串**（`apps/api/app/schemas/types.py` 里的 `BigIntStr`）。
 * 后端已经这么做了，所以正常请求根本不会走到本文件。
 * 它存在的唯一意义是：万一哪天有人新加了接口忘了套 `BigIntStr`，
 * 或者中间层（网关/日志回放/mock）把 ID 还原成了数字，这里兜一下，
 * 避免又出现"id 尾数悄悄变了 → 拼 URL 404"这种静默故障。
 *
 * ## 为什么必须先处理文本，而不能 parse 之后再转换
 *
 * 精度丢失发生在 `JSON.parse` **内部**，事后再遍历对象毫无意义：
 *
 *     JSON.parse('{"id":375228939615866880}')   // → { id: 375228939615866900 }
 *     String(parsed.id)                         // → "375228939615866900"  ← 已经错了，转换救不回来
 *
 * 所以**绝不能**写"解析出 number → 转 BigInt → 再转字符串"的还原逻辑：
 * BigInt(375228939615866900) 得到的仍是错的数字，而且给调用方一种"已修好"的错觉，
 * 比不做更危险。唯一正确的时机是 parse 之前 —— 给裸数字字面量补上引号，
 * 让 `JSON.parse` 直接产出字符串。
 *
 * ## 实现
 *
 * 只匹配「出现在 JSON 值位置」的、16 位及以上的裸数字：
 *
 *     :375228939615866880   →   :"375228939615866880"
 *
 * `:` `,` `[` 之后跟的长数字才是值；字符串内部的数字前面是普通字符或 `\"`，
 * `\d` 也不会跨越引号，因此不会误伤（例如 `{"phone":"13800000000"}` 不动它）。
 * 16 位是安全阈值：JS 安全整数上限 9007199254740991 是 16 位，
 * 而雪花 ID 是 18~19 位，两个量级完全分得开。
 */

/** 值位置的裸长整数：前面是 `:` / `,` / `[`，后面是 `,` / `}` / `]` 或空白。 */
const BARE_BIGINT = /([:,\[])\s*(\d{16,})(?=\s*[,}\]])/g;

export function parseJsonSafe<T>(text: string): T {
  return JSON.parse(text.replace(BARE_BIGINT, '$1"$2"')) as T;
}

/**
 * 判断一个运行时的值是否"看起来是 ID"。
 *
 * 只用于**开发期告警**（见 api.ts 的 dev 断言），不参与业务逻辑。
 * 目的：一旦后端有接口漏了 `BigIntStr`，在控制台立刻看到提示，而不是等线上 404。
 */
export function looksLikeUnsafeId(value: unknown): boolean {
  return typeof value === "number" && Number.isSafeInteger(value) === false;
}
